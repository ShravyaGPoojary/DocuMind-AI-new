from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class ChatSourceItem(BaseModel):
    """Source chunk metadata cited by the RAG pipeline."""

    chunk_id: int = Field(..., description="SQLite primary key ID of chunk")
    document_id: str = Field(..., description="UUID of the source document")
    chunk_index: int = Field(..., description="Index of chunk within the document")
    content: str = Field(..., description="Text content of the retrieved chunk")
    filename: str = Field(..., description="Filename of the source document")
    source_pages: Optional[str] = Field(None, description="Page number(s) if applicable")
    slide_number: Optional[int] = Field(None, description="Slide number if applicable")
    score: float = Field(..., description="Cosine similarity score (0.0 to 1.0)")


class ChatRequest(BaseModel):
    """Request payload for RAG document question answering."""

    question: str = Field(..., min_length=1, description="Question text to answer from documents")
    document_id: Optional[str] = Field(
        None, description="Optional document UUID to filter retrieval to a single document"
    )
    document_ids: Optional[List[str]] = Field(
        None, description="Optional list of document UUIDs to filter retrieval across multiple documents"
    )
    top_k: Optional[int] = Field(
        5, ge=1, le=20, description="Number of context chunks to retrieve (1-20)"
    )
    conversation_id: Optional[str] = Field(
        None, description="Optional conversation UUID to append to existing conversation"
    )
    provider: Optional[str] = Field(
        None, description="Optional LLM provider ('groq' or 'ollama'). Defaults to configured LLM_PROVIDER."
    )
    model: Optional[str] = Field(
        None, description="Optional model name override for answer generation"
    )


class ChatResponse(BaseModel):
    """Grounded answer and source citations returned by RAG."""

    answer: str = Field(..., description="Answer generated by LLM based strictly on document context")
    sources: List[ChatSourceItem] = Field(
        default_factory=list, description="List of retrieved source chunks used as context"
    )
    conversation_id: str = Field(..., description="UUID of the persisted conversation thread")
    model: str = Field(..., description="LLM model name used for generation")
    provider: Optional[str] = Field("groq", description="LLM provider used for generation ('groq' or 'ollama')")
    question: str = Field(..., description="The original user question")
    document_id: Optional[str] = Field(None, description="Primary document ID if scoped to single document")
    document_ids: List[str] = Field(default_factory=list, description="List of document UUIDs in retrieval scope")


class MessageSchema(BaseModel):
    """A single persisted message in a conversation thread."""

    id: str
    conversation_id: str
    role: str
    content: str
    sources: List[ChatSourceItem] = Field(default_factory=list)
    created_at: str


class ConversationSummarySchema(BaseModel):
    """Overview summary of a persisted conversation."""

    id: str
    title: str
    document_id: Optional[str] = None
    document_ids: List[str] = Field(default_factory=list)
    created_at: str
    updated_at: str
    message_count: int


class ConversationDetailResponse(BaseModel):
    """Full conversation thread with all ordered messages."""

    id: str
    title: str
    document_id: Optional[str] = None
    document_ids: List[str] = Field(default_factory=list)
    messages: List[MessageSchema] = Field(default_factory=list)


class ConversationListResponse(BaseModel):
    """List of all conversations."""

    total: int
    conversations: List[ConversationSummarySchema] = Field(default_factory=list)

